-- RF-A35: audit trail of sensitive administrative actions (actor, role, action, entity,
-- result, correlation and trusted IP). Append-only: no updated_at.

CREATE TABLE IF NOT EXISTS admin_audit_events (
    admin_audit_event_id  UUID            NOT NULL,                        -- eventId generated by the application
    actor_user_id         INT,                                             -- authenticated user who ran or attempted the action; NULL without an actor. No FK: the event never changes if the user is deleted
    actor_role            VARCHAR(30),                                     -- actor's role at the time of the action; NULL without an actor
    action                VARCHAR(100)    NOT NULL,                        -- action of the sensitive-action catalog (e.g. user.role_changed)
    entity_type           VARCHAR(50),                                     -- type of the affected entity (e.g. user, setting)
    entity_id             VARCHAR(64),                                     -- reference of the affected entity; NULL when it does not apply or is unknown
    result                VARCHAR(20)     NOT NULL,                        -- success | denied | failed
    status_code           SMALLINT,                                        -- HTTP status the request ended with
    correlation_id        VARCHAR(64)     NOT NULL,                        -- request identifier (X-Request-Id header)
    ip_address            INET,                                            -- client IP, only through a trusted proxy (TRUST_PROXY) or a direct connection
    metadata              JSONB           NOT NULL DEFAULT '{}',           -- allowed metadata of the action; never secrets, tokens or personal data
    occurred_at           TIMESTAMPTZ     NOT NULL,                        -- when the action finished
    created_at            TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    PRIMARY KEY (admin_audit_event_id),
    CONSTRAINT chk_admin_audit_events_result CHECK (result IN ('success', 'denied', 'failed'))
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_events_occurred_at    ON admin_audit_events(occurred_at);
CREATE INDEX IF NOT EXISTS idx_admin_audit_events_actor_user_id  ON admin_audit_events(actor_user_id);
CREATE INDEX IF NOT EXISTS idx_admin_audit_events_action         ON admin_audit_events(action);
CREATE INDEX IF NOT EXISTS idx_admin_audit_events_entity         ON admin_audit_events(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_admin_audit_events_correlation_id ON admin_audit_events(correlation_id);

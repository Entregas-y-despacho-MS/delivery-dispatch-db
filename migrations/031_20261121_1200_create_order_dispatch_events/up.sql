-- RF-A36 (ES-69): append-only history of business events per order and dispatch (creation,
-- assignment, status changes). Immutable by two layers: triggers that block UPDATE and DELETE,
-- and an application role (dispatch_app) that is only granted SELECT and INSERT.

CREATE TABLE IF NOT EXISTS order_dispatch_events (
    order_dispatch_event_id  UUID            NOT NULL,                        -- eventId generated by the application (idempotent insert)
    source_order_ref         VARCHAR(100)    NOT NULL,                        -- order reference in the source system (dispatches.source_order_ref). No FK: one order can have several dispatches
    dispatch_id              INT,                                             -- dispatch the event belongs to; NULL for events before the dispatch exists
    route_batch_id           INT,                                             -- route batch involved, when there is one
    actor_user_id            INT,                                             -- user who caused the event; NULL when the system did
    actor_role               VARCHAR(30),                                     -- actor's role at the time of the event; 'system' without a user
    action                   VARCHAR(100)    NOT NULL,                        -- event name (e.g. dispatch.created, dispatch.status_changed)
    previous_status          VARCHAR(50),                                     -- status code before the event; NULL when it does not apply
    new_status               VARCHAR(50),                                     -- status code after the event; NULL when it does not apply
    result                   VARCHAR(20)     NOT NULL,                        -- success | denied | failed
    correlation_id           VARCHAR(64)     NOT NULL,                        -- request identifier (X-Request-Id header)
    detail                   JSONB           NOT NULL DEFAULT '{}',           -- sanitized detail; never secrets, tokens or the full payload
    occurred_at              TIMESTAMPTZ     NOT NULL,                        -- when the event happened
    created_at               TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    PRIMARY KEY (order_dispatch_event_id),
    FOREIGN KEY (dispatch_id)    REFERENCES dispatches(dispatch_id)       ON DELETE RESTRICT,
    FOREIGN KEY (route_batch_id) REFERENCES route_batches(route_batch_id) ON DELETE RESTRICT,
    FOREIGN KEY (actor_user_id)  REFERENCES users(user_id)                ON DELETE RESTRICT,
    CONSTRAINT chk_order_dispatch_events_result CHECK (result IN ('success', 'denied', 'failed')),
    CONSTRAINT chk_order_dispatch_events_detail CHECK (jsonb_typeof(detail) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_order_dispatch_events_dispatch_occurred ON order_dispatch_events(dispatch_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_order_dispatch_events_order_occurred    ON order_dispatch_events(source_order_ref, occurred_at);
CREATE INDEX IF NOT EXISTS idx_order_dispatch_events_correlation_id    ON order_dispatch_events(correlation_id);
CREATE INDEX IF NOT EXISTS idx_order_dispatch_events_route_batch_id    ON order_dispatch_events(route_batch_id);
CREATE INDEX IF NOT EXISTS idx_order_dispatch_events_actor_user_id     ON order_dispatch_events(actor_user_id);

CREATE OR REPLACE FUNCTION fn_order_dispatch_events_prevent_update() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'order_dispatch_events is append-only: UPDATE is not allowed';
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_order_dispatch_events_prevent_delete() RETURNS TRIGGER AS $$
BEGIN
    IF COALESCE(current_setting('app.allow_event_purge', true), '') = 'on' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'order_dispatch_events is append-only: DELETE is not allowed';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_order_dispatch_events_prevent_update ON order_dispatch_events;
CREATE TRIGGER trg_order_dispatch_events_prevent_update
    BEFORE UPDATE ON order_dispatch_events
    FOR EACH ROW EXECUTE FUNCTION fn_order_dispatch_events_prevent_update();

DROP TRIGGER IF EXISTS trg_order_dispatch_events_prevent_delete ON order_dispatch_events;
CREATE TRIGGER trg_order_dispatch_events_prevent_delete
    BEFORE DELETE ON order_dispatch_events
    FOR EACH ROW EXECUTE FUNCTION fn_order_dispatch_events_prevent_delete();

-- Application role: can read and append, nothing else. The backend connection user must be
-- a member of it (or be granted the same privileges). Roles are cluster-wide, so it is guarded.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dispatch_app') THEN
        CREATE ROLE dispatch_app NOLOGIN;
    END IF;
END $$;

REVOKE ALL ON order_dispatch_events FROM dispatch_app;
GRANT SELECT, INSERT ON order_dispatch_events TO dispatch_app;

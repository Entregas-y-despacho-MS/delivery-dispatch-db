-- ST-36.3 — Expo/FCM push tokens of the drivers' devices (RF-U10).

CREATE TABLE IF NOT EXISTS push_tokens (
    push_token_id  SERIAL,
    user_id        INT             NOT NULL,                       -- user that owns this device registration
    device_id      VARCHAR(100)    NOT NULL,                       -- stable identifier of the device, generated by the mobile app
    token          VARCHAR(255)    NOT NULL,                       -- push provider token of the device (Expo or FCM)
    platform       VARCHAR(10)     NOT NULL,                       -- device operating system
    last_used_at   TIMESTAMPTZ     NOT NULL DEFAULT NOW(),         -- last time the app registered this token
    revoked_at     TIMESTAMPTZ,                                    -- NULL = active; set on logout or when the provider rejects the token
    created_at     TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    PRIMARY KEY (push_token_id),
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT uq_push_tokens_user_device UNIQUE (user_id, device_id),
    CONSTRAINT chk_push_tokens_platform CHECK (platform IN ('ios', 'android'))
);

-- A token belongs to a phone, not to a person: while it is active it can have only one owner.
CREATE UNIQUE INDEX IF NOT EXISTS uq_push_tokens_active_token ON push_tokens(token) WHERE revoked_at IS NULL;
